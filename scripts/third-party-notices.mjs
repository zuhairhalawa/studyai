#!/usr/bin/env node
/**
 * Writes THIRD-PARTY-NOTICES.md: the production dependencies (what ships in the app and the Worker) with their licenses, and the
 * full text of the font licenses that must travel with the fonts. Run `pnpm notices` after changing dependencies. Development
 * tools (test runners, bundlers) are not shipped and are not listed.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';

const args = ['licenses', 'list', '--prod', '--json'];
const opts = { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 };
// Started through pnpm, run the same pnpm directly (no shell); started by hand, find it on the path.
const via = process.env.npm_execpath && /pnpm/i.test(process.env.npm_execpath) && /\.c?js$/i.test(process.env.npm_execpath) ? process.env.npm_execpath : undefined;
const raw = via ? execFileSync(process.execPath, [via, ...args], opts) : execFileSync(process.platform === 'win32' ? 'pnpm.cmd' : 'pnpm', args, { ...opts, shell: process.platform === 'win32' });
/** @type {Record<string, { name: string; versions: string[]; paths: string[]; author?: string; homepage?: string }[]>} */
const byLicense = JSON.parse(raw);

const lines = [];
lines.push('# Third-party notices', '');
lines.push('StudyAI ships the open-source packages below. Each is used under its own license; none of them is changed. This file is generated by `pnpm notices` from the production dependencies, so it lists what is in the built app and the Worker, not the tools used to build and test them.', '');
const total = Object.values(byLicense).reduce((n, p) => n + p.length, 0);
lines.push(`${total} packages: ${Object.entries(byLicense).sort((a, b) => b[1].length - a[1].length).map(([l, p]) => `${l} (${p.length})`).join(', ')}.`, '');

for (const [license, pkgs] of Object.entries(byLicense).sort((a, b) => b[1].length - a[1].length)) {
  lines.push(`## ${license}`, '');
  for (const p of pkgs.sort((a, b) => a.name.localeCompare(b.name))) {
    const home = p.homepage ? ` — ${p.homepage}` : '';
    lines.push(`- ${p.name} ${p.versions.join(', ')}${p.author ? ` (${p.author})` : ''}${home}`);
  }
  lines.push('');
}

// The SIL Open Font License asks that its text and the copyright notice go with the font files.
const fonts = (byLicense['OFL-1.1'] ?? []).sort((a, b) => a.name.localeCompare(b.name));
if (fonts.length > 0) {
  lines.push('## Font licenses (SIL Open Font License 1.1)', '');
  lines.push('The fonts are bundled with the app (no request goes to a font server). Their license texts:', '');
  for (const f of fonts) {
    const file = (f.paths ?? []).map((p) => `${p}/LICENSE`).find((p) => existsSync(p));
    lines.push(`### ${f.name} ${f.versions.join(', ')}`, '');
    lines.push('```text', file ? readFileSync(file, 'utf8').trim() : 'License text not found in the package; see the homepage above.', '```', '');
  }
}
writeFileSync('THIRD-PARTY-NOTICES.md', lines.join('\n'), 'utf8');
console.log(`THIRD-PARTY-NOTICES.md: ${total} packages, ${fonts.length} font licenses`);
